"""Apply brand.json everywhere: icons, launchers, Cinema 4D plugin, Blender add-on, desktop app.

    py -3.13 tools/apply_brand.py              # everything that's installed on this machine
    py -3.13 tools/apply_brand.py --no-app     # skip building the desktop app (faster while iterating)

Run it after any change to brand.json or the icon SVG. Restart Cinema 4D / Blender afterwards.
"""
import argparse
import glob
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "server"))
from brand import BRAND  # noqa: E402

MARK = "rem generated by tools/apply_brand.py"


def run(script, *args):
    print("\n== %s %s" % (script, " ".join(args)))
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", script)] + list(args))
    return r.returncode == 0


def launchers():
    for old in glob.glob(os.path.join(ROOT, "*.bat")):  # drop launchers from a previous brand name
        with open(old, "r", encoding="utf-8", errors="replace") as fh:
            if MARK in fh.read():
                os.remove(old)
    name, exe = BRAND["name"], BRAND["exe_name"]
    app = r"%%LOCALAPPDATA%%\Programs\%s\%s.exe" % (exe, exe)
    main = ("@echo off\r\n%s\r\nrem %s: opens the desktop app if installed, otherwise starts the server and a browser tab.\r\n"
            "cd /d \"%%~dp0\"\r\nif exist \"%s\" (\r\n  start \"\" \"%s\"\r\n) else (\r\n"
            "  start \"\" pyw -3 \"%%~dp0server\\bridge2.py\"\r\n)\r\n") % (MARK, name, app, app)
    console = ("@echo off\r\n%s\r\nrem %s with a console window (shows the server log).\r\ncd /d \"%%~dp0\"\r\n"
               "py -3 \"%%~dp0server\\bridge2.py\"\r\npause\r\n") % (MARK, name)
    for fname, text in ((name + ".bat", main), (name + " (console).bat", console)):
        with open(os.path.join(ROOT, fname), "w", encoding="utf-8", newline="") as fh:
            fh.write(text)
    print("\n== launchers: %s.bat, %s (console).bat" % (name, name))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--no-app", action="store_true")
    ap.add_argument("--no-c4d", action="store_true")
    ap.add_argument("--no-blender", action="store_true")
    args = ap.parse_args()
    print("Brand: %s (exe %s, ports %s)" % (BRAND["name"], BRAND["exe_name"], BRAND["ports"]))
    ok = run("make_icons.py")
    launchers()
    maxon = glob.glob(os.path.join(os.environ.get("APPDATA", ""), "Maxon", "Maxon Cinema 4D *_*"))
    if not args.no_c4d and maxon:
        ok &= run("install_c4d_plugin.py")
    elif not args.no_c4d:
        print("\n== Cinema 4D not found, skipped the plugin")
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from install_blender_addon import DEFAULT_BLENDER
    if not args.no_blender and DEFAULT_BLENDER:
        ok &= run("install_blender_addon.py")
    elif not args.no_blender:
        print("\n== Blender not found automatically; run tools/install_blender_addon.py --blender <path to blender.exe>")
    if not args.no_app:
        ok &= run("build_app.py")
    print("\nDone." if ok else "\nFinished with errors (see above).")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
